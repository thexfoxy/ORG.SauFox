import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const works = JSON.parse(await readFile(join(root, 'work-routes.json'), 'utf8'));
const template = await readFile(join(root, 'work.html'), 'utf8');
const paths = {};
const escape = (s) => String(s).replace(/[&<>"']/g, (c) => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
for (const work of works) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(work.id) || Object.hasOwn(paths, work.id)) throw new Error('Invalid or duplicate work ID');
  const path = `/works/${work.id}`;
  paths[work.id] = path;
  const html = template.replace('<head>', '<head>\n  <base href="/">')
    .replace('<title>SauFox Entertainment</title>', `<title>${escape(work.title)} · SauFox Entertainment</title>\n  <link rel="canonical" href="https://saufoxentertainment.ir${path}">`);
  await mkdir(join(root, 'works'), { recursive: true });
  await writeFile(join(root, 'works', `${work.id}.html`), html);
}
await writeFile(join(root, 'js/work-paths.js'), `// Generated by scripts/generate-work-pages.mjs.\nwindow.SAUFOX_WORK_PATHS = Object.freeze(${JSON.stringify(paths)});\n`);
console.log(`Generated ${works.length} work page(s).`);
